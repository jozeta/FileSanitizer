export function isBuiltinPattern(patternId: string): boolean {
  return BUILTIN_FORMAT_PATTERNS.some(p => p.id === patternId);
}

export function getDefaultBuiltinPattern(patternId: string): PatternDefinition | undefined {
  const p = BUILTIN_FORMAT_PATTERNS.find(b => b.id === patternId);
  return p ? { ...p } : undefined;
}
